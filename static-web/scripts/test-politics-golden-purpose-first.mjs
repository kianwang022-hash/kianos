import { spawn } from 'node:child_process';
import { chromium } from 'playwright';

const PORT = 4326;
const BASE = `http://127.0.0.1:${PORT}`;
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
const check = (condition, name, detail = '') => {
  if (!condition) throw new Error(`POLITICS_GOLDEN_PURPOSE_FAIL:${name}${detail ? `:${detail}` : ''}`);
  console.log(`PASS ${name}${detail ? ` · ${detail}` : ''}`);
};

async function waitForServer() {
  for (let index = 0; index < 80; index += 1) {
    try {
      const response = await fetch(`${BASE}/politics/`);
      if (response.ok) return;
    } catch {}
    await sleep(250);
  }
  throw new Error('POLITICS_GOLDEN_PREVIEW_SERVER_NOT_READY');
}

const server = spawn('npm', ['run', 'preview', '--', '--host', '127.0.0.1', '--port', String(PORT)], {
  cwd: process.cwd(),
  stdio: ['ignore', 'pipe', 'pipe'],
  detached: process.platform !== 'win32'
});

let browser;
try {
  await waitForServer();
  browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1512, height: 982 } });
  const page = await context.newPage();
  await page.goto(`${BASE}/politics/marxism/ch00/`, { waitUntil: 'networkidle' });

  const workspace = page.locator('[data-politics-cognitive-workspace]');
  await workspace.waitFor({ state: 'visible' });

  const s01 = workspace.locator('[data-workspace-unit][data-unit-id="POL27-CF-MARX-C00-S01"]');
  await s01.waitFor({ state: 'visible' });
  check((await s01.getAttribute('data-politics-representation')) === 'SIMPLE_CHAIN_WHEN_CLEARER', 's01_visual_is_explicit_exception');
  check(await s01.locator('.purposeChain').isVisible(), 's01_simple_chain_visible');
  const s01TitleSize = Number.parseFloat(await s01.locator('[data-stage="ORIENT"] > h2').evaluate((node) => getComputedStyle(node).fontSize));
  check(s01TitleSize >= 30, 's01_main_title_readable', `${s01TitleSize}px`);

  await workspace.locator('[data-workspace-unit-tab="1"]').click();
  const s02 = workspace.locator('[data-workspace-unit][data-unit-id="POL27-CF-MARX-C00-S02"]');
  await s02.waitFor({ state: 'visible' });
  check((await s02.getAttribute('data-politics-representation')) === 'TEXT_DEFAULT', 's02_is_text_default');

  const peers = await s02.locator('.featureNames > b').allTextContents();
  check(JSON.stringify(peers) === JSON.stringify(['科学性', '人民性', '实践性', '发展性']), 's02_peer_characteristics_are_exact', JSON.stringify(peers));
  check(!peers.includes('革命性'), 's02_revolutionarity_not_misdrawn_as_peer');

  const relationText = (await s02.locator('.readableRelations').innerText()).replace(/\s+/g, ' ');
  check(relationText.includes('人民性、实践性、发展性：集中体现马克思主义的革命性'), 's02_revolutionary_relation_explicit');
  check(relationText.includes('科学性：为革命性提供科学基础'), 's02_scientific_basis_relation_explicit');
  check(relationText.includes('科学性与革命性：高度统一'), 's02_unity_relation_explicit');

  const hiddenGraphs = await s02.locator('.goldenGraph').evaluateAll((nodes) => nodes.every((node) => getComputedStyle(node).display === 'none' || node.getClientRects().length === 0));
  check(hiddenGraphs, 's02_generated_graphs_do_not_own_first_view');

  // Lock to the purpose-first block generated by this Golden Page layer.
  // Generic runtime still owns unrelated `.valueRows`, so DOM position is not semantic identity.
  const valueBlock = s02.locator('.purposeTextMap .valueRows.readableConcepts');
  await valueBlock.waitFor({ state: 'visible' });
  const valueLabels = await valueBlock.locator(':scope > .valueRow > b').allTextContents();
  check(JSON.stringify(valueLabels) === JSON.stringify(['认识工具', '行动指南', '科学真理']), 's02_contemporary_value_is_readable_text', JSON.stringify(valueLabels));

  const exactText = (await s02.locator('.firstRoundExact').innerText()).replace(/\s+/g, ' ');
  check(exactText.includes('人民性是马克思主义的本质属性'), 's02_first_round_exact_visible');
  check(exactText.includes('人民至上是马克思主义的政治立场'), 's02_first_round_exact_complete');

  const mainTitleSize = Number.parseFloat(await s02.locator('[data-stage="ORIENT"] > h2').evaluate((node) => getComputedStyle(node).fontSize));
  const peerSize = Number.parseFloat(await s02.locator('.featureNames > b').first().evaluate((node) => getComputedStyle(node).fontSize));
  const relationSize = Number.parseFloat(await s02.locator('.readableRelations p').first().evaluate((node) => getComputedStyle(node).fontSize));
  const exactSize = Number.parseFloat(await s02.locator('.firstRoundExact > p').first().evaluate((node) => getComputedStyle(node).fontSize));
  check(mainTitleSize >= 30, 's02_main_title_readable', `${mainTitleSize}px`);
  check(peerSize >= 18, 's02_peer_type_readable', `${peerSize}px`);
  check(relationSize >= 16, 's02_relation_type_readable', `${relationSize}px`);
  check(exactSize >= 16, 's02_exact_type_readable', `${exactSize}px`);

  await context.close();
  console.log('POLITICS_GOLDEN_PURPOSE_FIRST_PASS');
} finally {
  await browser?.close().catch(() => {});
  if (process.platform !== 'win32' && server.pid) {
    try { process.kill(-server.pid, 'SIGTERM'); } catch {}
  } else {
    try { server.kill('SIGTERM'); } catch {}
  }
  server.stdout?.destroy();
  server.stderr?.destroy();
  await Promise.race([new Promise((resolve) => server.once('exit', resolve)), sleep(1000)]);
  if (server.exitCode === null) {
    if (process.platform !== 'win32' && server.pid) {
      try { process.kill(-server.pid, 'SIGKILL'); } catch {}
    } else {
      try { server.kill('SIGKILL'); } catch {}
    }
  }
}
